//! Розпізнавання `node_modules` за маркерами (T-049) + активність проєкту (T-052).
//!
//! architecture.md §6.1: структурний детектор — патерн каталогу + маркер
//! `package.json` у батьківській теці проєкту (поруч із `node_modules`).
//!
//! DoD T-049:
//! - хибних спрацювань на корпусі без маркера — 0;
//! - вкладені `node_modules` не дублюються (лише **outermost** корінь).
//!
//! DoD T-052: свіжі правки джерел поза `node_modules` → проєкт **активний** →
//! артефакти [`SafetyLevel::ReviewRecommended`] (не safe-to-bulk).
//!
//! Без I/O: маркери й дати з індексу.

use std::collections::{HashMap, HashSet};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::RwLock;

use super::contract::{Detector, DetectorId};
